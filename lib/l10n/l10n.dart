class L10nDelegate extends LocalizationsDelegate<L10n> {
  const L10nDelegate();

  @override
  bool isSupported(Locale locale) =>
      locale.languageCode == 'fr' || locale.languageCode == 'en';

  @override
  Future<L10n> load(Locale locale) => SynchronousFuture<L10n>(L10n(locale));

  @override
  bool shouldReload(covariant LocalizationsDelegate<L10n> old) => false;
}

extension L10nContext on BuildContext {
  L10n get l10n => L10n.of(this);
  String tr(String source) => L10n.of(this).t(source);
}
